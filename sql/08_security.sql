-- =========================================================
-- Snowflake Security / RBAC Demo
-- =========================================================

-- Create a read-only role
CREATE ROLE IF NOT EXISTS SNOWFLAKE_LAB_READONLY;

-- Allow access to the database
GRANT USAGE
ON DATABASE SNOWFLAKE_LAB
TO ROLE SNOWFLAKE_LAB_READONLY;

-- Allow access to schemas
GRANT USAGE
ON SCHEMA SNOWFLAKE_LAB.RAW
TO ROLE SNOWFLAKE_LAB_READONLY;

GRANT USAGE
ON SCHEMA SNOWFLAKE_LAB.ANALYTICS
TO ROLE SNOWFLAKE_LAB_READONLY;

-- Allow reading current tables
GRANT SELECT
ON ALL TABLES
IN SCHEMA SNOWFLAKE_LAB.RAW
TO ROLE SNOWFLAKE_LAB_READONLY;

GRANT SELECT
ON ALL TABLES
IN SCHEMA SNOWFLAKE_LAB.ANALYTICS
TO ROLE SNOWFLAKE_LAB_READONLY;

-- Automatically grant SELECT on future tables
GRANT SELECT
ON FUTURE TABLES
IN SCHEMA SNOWFLAKE_LAB.RAW
TO ROLE SNOWFLAKE_LAB_READONLY;

GRANT SELECT
ON FUTURE TABLES
IN SCHEMA SNOWFLAKE_LAB.ANALYTICS
TO ROLE SNOWFLAKE_LAB_READONLY;

-- Inspect grants
SHOW GRANTS TO ROLE SNOWFLAKE_LAB_READONLY;