--create customers table
CREATE OR REPLACE TABLE SNOWFLAKE_LAB.RAW.CUSTOMERS (
    CUSTOMER_ID NUMBER,
    FIRST_NAME VARCHAR,
    LAST_NAME VARCHAR,
    EMAIL VARCHAR
);

--create csv file format
CREATE OR REPLACE FILE FORMAT SNOWFLAKE_LAB.RAW.CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"';

--create stage
CREATE OR REPLACE STAGE SNOWFLAKE_LAB.RAW.CUSTOMER_STAGE
    FILE_FORMAT = SNOWFLAKE_LAB.RAW.CSV_FORMAT;